<script setup lang="ts">
import { computed, watch, inject, onMounted, onBeforeUnmount } from 'vue'
import { useRoute, useRouter } from 'vue-router'
import { useMediaQuery, useOnline } from '@vueuse/core'
import { LoadingIndicator } from 'frappe-ui'
import AppFrame from './AppFrame.vue'
import { state, firstRoute, person, org } from '../lib/store'
import { sync, loadData, listen } from '../lib/sync'
import { setTheme } from '../lib/theme'
// Photos on some people's avatars
import '../lib/avatarPhotos'

// The app around every Studio page: the prototype's App.vue (logic) and AppFrame (sidebar, panels, dialogs).
// Each page's block tree is AppShell with the page's blocks in its default slot and the sidebar (the app_sidebar
// Studio Component) in its `sidebar` slot. `bare` pages (login, welcome, setup, invite) have no sidebar.
const props = defineProps<{ bare?: boolean }>()

const route = useRoute()
const router = useRouter()

// The data: loaded once, saved as it changes, and kept live (lib/sync.ts)
loadData()
listen(inject('socket', null))

// "View as" is gone: you are whoever is signed in to Frappe (state.me is set from the server).
// Admin, Swarali, Neha and the New user are real logins.

const isMobile = useMediaQuery('(max-width: 767px)')

// Offline banner: only when the browser really loses its connection (the "Connection" demo variant was removed)
const browserOnline = useOnline()
const offline = computed(() => !browserOnline.value)
const bare = computed(() => !!props.bare)

// First visits: the new user goes to /welcome, an invited person to their invite.
watch(
  () => sync.ready,
  (ready) => {
    if (!ready || bare.value || sync.routed) return
    sync.routed = true
    const to = firstRoute()
    if (to !== '/' && route.path !== to) router.replace(to)
  },
  { immediate: true },
)

// The workspace layer is always on (decided, Round 235): workspaces above projects (switcher at the top of the
// sidebar, a second workspace "Acme Studio", workspace invites, projects joined only by invitation).
org.on = true

// A new user who hasn't finished welcome always lands there, whatever the URL.
watch(
  () => [sync.ready, state.me, route.path],
  () => {
    if (sync.ready && state.me === 'newbie' && !person('newbie')?.onboarded && !bare.value) router.replace('/welcome')
  },
  { immediate: true },
)

function typing(e: KeyboardEvent) {
  const el = e.target as HTMLElement
  return ['INPUT', 'TEXTAREA', 'SELECT'].includes(el?.tagName) || el?.isContentEditable
}
function onKey(e: KeyboardEvent) {
  if (bare.value || !sync.ready) return
  if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') {
    e.preventDefault()
    state.ui.search = true
    return
  }
  if (typing(e) || e.metaKey || e.ctrlKey || e.altKey) return
  if (e.key === 'c') {
    e.preventDefault()
    state.ui.quickAdd = true
  }
}
onMounted(() => {
  window.addEventListener('keydown', onKey)
  // Light mode by default. People can switch in Settings → Appearance.
  setTheme('light')
})
onBeforeUnmount(() => window.removeEventListener('keydown', onKey))
</script>

<template>
  <AppFrame v-if="sync.ready" :bare="bare" :is-mobile="isMobile" :offline="offline">
    <template #sidebar><slot name="sidebar" /></template>
    <slot />
  </AppFrame>
  <div v-else class="flex h-full w-full items-center justify-center bg-surface-base text-ink-gray-5">
    <p v-if="sync.error" class="max-w-sm text-center text-p-base text-ink-red-4">{{ sync.error }}</p>
    <LoadingIndicator v-else class="size-5" />
  </div>
</template>

